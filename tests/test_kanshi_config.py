"""Kanshi config generated from the saved profiles (issue #51).

The make/model/serial triples are the real ones recorded in
``test_niri_identifier.py``.  kanshi names an output ``"<make> <model>
<serial>"`` (``Unknown`` for a missing field) and ``fnmatch()``es the
criteria against it.
"""

from __future__ import annotations

from monique import kanshi_config
from monique.kanshi_config import (
    generate_kanshi_config,
    kanshi_monitors_path,
    write_kanshi_config,
)
from monique.models import (
    MonitorConfig,
    PositionMode,
    Profile,
    ResolutionMode,
    ScaleMode,
    Transform,
)
from monique.profile_manager import ProfileManager
from monique.utils import save_app_settings


def _lg(**kw) -> MonitorConfig:
    base = dict(
        name="DP-2", description="LG Electronics LG HDR 4K 0x00078A89",
        make="LG Electronics", model="LG HDR 4K", serial="0x00078A89",
        width=3840, height=2160, refresh_rate=60.0, scale=1.25,
        position_mode=PositionMode.EXPLICIT,
    )
    return MonitorConfig(**{**base, **kw})


def _aoc(**kw) -> MonitorConfig:
    base = dict(
        name="DP-3", description="AOC 2757 AXSD79A000536",
        make="PNP(AOC)", model="2757", serial="AXSD79A000536",
        width=1920, height=1080, x=3840,
    )
    return MonitorConfig(**{**base, **kw})


def _panel(**kw) -> MonitorConfig:
    base = dict(
        name="eDP-2", description="AU Optronics 0x328E",
        make="AU Optronics", model="0x328E", serial="", enabled=False,
    )
    return MonitorConfig(**{**base, **kw})


def _gen(*profiles, use_description=True) -> str:
    return generate_kanshi_config(list(profiles), use_description)


# -- structure ----------------------------------------------------------

def test_profile_block_matches_the_documented_shape() -> None:
    text = _gen(Profile(name="LG+AOC", monitors=[_lg(), _panel()]))

    assert text == (
        "# Generated by Monique: https://github.com/ToRvaLDz/monique\n"
        'profile "LG+AOC" {\n'
        '    output "LG Electronics LG HDR 4K 0x00078A89" {\n'
        "        enable\n"
        "        mode 3840x2160@60.000Hz\n"
        "        position 0,0\n"
        "        scale 1.25\n"
        "        transform normal\n"
        "    }\n"
        '    output "AU Optronics 0x328E Unknown" disable\n'
        "}\n"
    )


def test_no_profiles_yields_only_the_header() -> None:
    assert _gen() == "# Generated by Monique: https://github.com/ToRvaLDz/monique\n"


def test_profiles_are_emitted_in_the_given_order() -> None:
    text = _gen(
        Profile(name="b", monitors=[_lg()]), Profile(name="a", monitors=[_lg()]),
    )

    assert text.index('profile "b"') < text.index('profile "a"')


# -- directives ---------------------------------------------------------

def test_preferred_mode_and_omitted_modes() -> None:
    preferred = _gen(Profile(name="p", monitors=[
        _lg(resolution_mode=ResolutionMode.PREFERRED)]))
    highres = _gen(Profile(name="p", monitors=[
        _lg(resolution_mode=ResolutionMode.HIGHRES)]))
    highrr = _gen(Profile(name="p", monitors=[
        _lg(resolution_mode=ResolutionMode.HIGHRR)]))

    assert "mode preferred" in preferred
    assert "mode " not in highres
    assert "mode " not in highrr


def test_position_and_scale_only_when_explicit() -> None:
    text = _gen(Profile(name="p", monitors=[
        _lg(position_mode=PositionMode.AUTO_RIGHT, scale_mode=ScaleMode.AUTO)]))

    assert "position" not in text
    assert "scale" not in text


def test_position_is_x_comma_y() -> None:
    text = _gen(Profile(name="p", monitors=[_aoc(position_mode=PositionMode.EXPLICIT, y=-120)]))

    assert "position 3840,-120" in text


def test_fractional_refresh_rate_keeps_millihertz() -> None:
    text = _gen(Profile(name="p", monitors=[_lg(refresh_rate=59.94)]))

    assert "mode 3840x2160@59.940Hz" in text


def test_transforms_use_the_protocol_order() -> None:
    """kanshi hands the value to the protocol: 90 means 90 counter-clockwise."""
    expected = {
        Transform.NORMAL: "normal",
        Transform.ROTATE_90: "90",
        Transform.ROTATE_180: "180",
        Transform.ROTATE_270: "270",
        Transform.FLIPPED: "flipped",
        Transform.FLIPPED_90: "flipped-90",
        Transform.FLIPPED_180: "flipped-180",
        Transform.FLIPPED_270: "flipped-270",
    }
    for transform, word in expected.items():
        text = _gen(Profile(name="p", monitors=[_lg(transform=transform)]))
        assert f"        transform {word}\n" in text


