"""Serializzazione dei profili nella config monitor di Umbriel.

Umbriel legge una config TOML (``config.toml``) con una tabella
``[output."<selettore>"]`` per monitor; il file generato qui è incluso da
``config.toml`` (vedi ``ensure_umbriel_include``).  Il selettore è il connettore
oppure l'identità ``"<make> <model> <serial>"`` che Umbriel riporta come
``config_name``.

Il modulo non importa ``gi`` e non aggiunge nulla a ``MonitorConfig``.
"""

from __future__ import annotations

import copy
import logging
import os
import re
import tomllib
from pathlib import Path

from .config_paths import umbriel_monitors_path, umbriel_user_config_path
from .models import (
    VRR,
    MonitorConfig,
    PositionMode,
    Profile,
    ResolutionMode,
    ScaleMode,
    Transform,
    normalize_description,
)
from .utils import (
    backup_file,
    get_monitor_config_name,
    is_config_dir_overridden,
    write_text,
)

log = logging.getLogger(__name__)

HEADER = "# Generated by Monique: https://github.com/ToRvaLDz/monique"

# Intervallo di scala accettato da Umbriel
SCALE_MIN = 0.25
SCALE_MAX = 4.0

_CONTROL_CHARS = re.compile(r"[\x00-\x1f\x7f]")

_VRR_POLICY = {VRR.ON: "always", VRR.FULLSCREEN: "fullscreen"}
_VRR_FROM_POLICY = {v: k for k, v in _VRR_POLICY.items()}

# Stesso ordine del protocollo Wayland usato da Niri: i valori coincidono 1:1
_TRANSFORMS = MonitorConfig._NIRI_TRANSFORMS
_TRANSFORMS_INV = {v: k for k, v in _TRANSFORMS.items()}


def _quote(text: str) -> str:
    """Quote *text* as a TOML basic string.

    I caratteri di controllo (a capo compreso) diventano uno spazio: un nome
    modificato a mano non deve poter spezzare il file.
    """
    flat = _CONTROL_CHARS.sub(" ", text)
    return '"' + flat.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _identity(output: dict) -> str:
    """Join make, model and serial the way the other compositors do."""
    parts = (output.get("make"), output.get("model"), output.get("serial"))
    return normalize_description(" ".join(p for p in parts if p))


def umbriel_ids(outputs: list[dict]) -> dict[str, str]:
    """Map normalised description -> Umbriel ``config_name`` of live outputs."""
    return {
        _identity(out): out["config_name"]
        for out in outputs
        if out.get("config_name") and _identity(out)
    }


def _mode_text(mode: dict) -> str | None:
    """Render an Umbriel mode entry as the ``WxH@R`` string of ``mode``."""
    width, height = mode.get("width"), mode.get("height")
    if not (width and height):
        return None
    size = f"{width}x{height}"
    refresh = mode.get("refresh_mhz") or 0
    return f"{size}@{refresh / 1000.0:.3f}" if refresh > 0 else size


def umbriel_preferred(outputs: list[dict]) -> dict[str, str]:
    """Map description and connector -> preferred mode of the live outputs.

    Umbriel conserva il ``mode`` vivo quando la chiave sparisce dal file: per
    ottenere il modo preferito va scritto esplicitamente.  Una descrizione
    condivisa da più output (gemelli) è ambigua e resta fuori: vale il connettore.
    """
    found: dict[str, str] = {}
    # Anche un output senza modo preferito conta: un gemello non eredita il suo
    counts: dict[str, int] = {}
    for out in outputs:
        desc = _identity(out)
        if desc:
            counts[desc] = counts.get(desc, 0) + 1
    for out in outputs:
        mode = next((m for m in out.get("modes") or [] if m.get("preferred")), None)
        text = _mode_text(mode) if mode else None
        if not text:
            continue
        if out.get("name"):
            found[out["name"]] = text
        desc = _identity(out)
        if desc and counts[desc] == 1:
            found[desc] = text
    return found


def monitor_from_umbriel_output(data: dict) -> MonitorConfig:
    """Create a MonitorConfig from one entry of Umbriel's ``outputs`` reply."""
    modes = data.get("modes") or []
    current = next((m for m in modes if m.get("current")), {})
    refresh = round(current.get("refresh_mhz", 60000) / 1000.0, 3)
    enabled = bool(data.get("enabled", True))
    pos = data.get("position") or {}
    make, model, serial = (data.get(k) or "" for k in ("make", "model", "serial"))

    return MonitorConfig(
        name=data.get("name", ""),
        description=_identity(data),
        make=make,
        model=model,
        serial=serial,
        width=current.get("width", 1920),
        height=current.get("height", 1080),
        refresh_rate=refresh,
        resolution_mode=ResolutionMode.EXPLICIT,
        available_modes=[
            f"{m.get('width', 0)}x{m.get('height', 0)}"
            f"@{round(m.get('refresh_mhz', 0) / 1000.0, 3):.3f}Hz"
            for m in modes
        ],
        x=pos.get("x", 0),
        y=pos.get("y", 0),
        position_mode=PositionMode.EXPLICIT if enabled else PositionMode.AUTO,
        # f32 di Umbriel: 1.2 arriva come 1.2000000476837158
        scale=round(float(data.get("scale", 1.0)), 4),
        scale_mode=ScaleMode.EXPLICIT,
        transform=Transform(_TRANSFORMS_INV.get(data.get("transform"), 0)),
        enabled=enabled,
        vrr=VRR.ON if data.get("adaptive_sync") else VRR.OFF,
    )


def _selector(
    monitor: MonitorConfig, use_description: bool, ids: dict[str, str] | None,
) -> str:
    """Return the output table name for *monitor*.

    Un monitor senza descrizione non ha identità in Umbriel: connettore, mai
    un'identità ricostruita.  Con la descrizione vale il ``config_name`` letto
    dall'IPC; se manca (scollegato, IPC fallita, cross-write da un altro
    compositore) si ricostruisce offline, come fa ``outputDescriptor``.
    """
    if not (use_description and monitor.description):
        return monitor.name
    if ids and monitor.description in ids:
        return ids[monitor.description]
    return monitor.niri_native_description() or monitor.name


def _selectors(
    monitors: list[MonitorConfig], use_description: bool,
    ids: dict[str, str] | None,
) -> list[str]:
    """Pick one selector per monitor; twins fall back to their connectors.

    Due tabelle con lo stesso nome (Umbriel le confronta senza distinguere le
    maiuscole) rompono l'intero file, quindi i gemelli senza seriale ripiegano
    sui connettori.
    """
    picked = [_selector(m, use_description, ids) for m in monitors]
    lowered = [p.lower() for p in picked]
    return [
        m.name if lowered.count(low) > 1 else p
        for m, p, low in zip(monitors, picked, lowered)
    ]


def _scale(value: float) -> str:
    """Render the scale as a TOML float (``1`` would be an integer)."""
    return repr(round(min(max(value, SCALE_MIN), SCALE_MAX), 4))


def _mode(monitor: MonitorConfig) -> str:
    size = f"{monitor.width}x{monitor.height}"
    if monitor.refresh_rate <= 0:
        return size
    return f"{size}@{monitor.refresh_rate:.3f}"


def _preferred_mode(
    monitor: MonitorConfig, use_description: bool, preferred: dict[str, str] | None,
) -> str | None:
    """Return the live preferred mode of *monitor*, None without live data."""
    if not preferred:
        return None
    if use_description and monitor.description in preferred:
        return preferred[monitor.description]
    return preferred.get(monitor.name)


def _output_lines(
    monitor: MonitorConfig, selector: str, preferred_mode: str | None = None,
) -> list[str]:
    """Render one table; every key Umbriel would keep live is written explicitly.

    Umbriel azzera scale, enabled e position quando la chiave sparisce, ma
    conserva transform e mode: quelli vanno scritti sempre, anche ai valori
    di default.  Senza dati vivi il modo non preferito resta omesso.
    """
    lines = [f"[output.{_quote(selector)}]"]
    if not monitor.enabled:
        return [*lines, "enabled = false"]

    lines.append("enabled = true")
    if monitor.resolution_mode == ResolutionMode.EXPLICIT:
        lines.append(f'mode = "{_mode(monitor)}"')
    elif preferred_mode:
        lines.append(f'mode = "{preferred_mode}"')
    if monitor.position_mode == PositionMode.EXPLICIT:
        lines.append(f"position = [{monitor.x}, {monitor.y}]")
    if monitor.scale_mode == ScaleMode.EXPLICIT:
        lines.append(f"scale = {_scale(monitor.scale)}")
    hdr = "on" if monitor.color_management in ("hdr", "hdredid") else "off"
    lines += [
        f'transform = "{_TRANSFORMS[monitor.transform.value]}"',
        f'vrr = "{_VRR_POLICY.get(monitor.vrr, "disabled")}"',
        f'hdr = "{hdr}"',
        f"bit_depth = {10 if monitor.bitdepth == 10 else 8}",
        f"focus_at_startup = {'true' if monitor.focus_at_startup else 'false'}",
    ]
    return lines


def generate_umbriel_config(
    profile: Profile, use_description: bool,
    ids: dict[str, str] | None = None,
    preferred: dict[str, str] | None = None,
) -> str:
    """Serialize *profile* as the TOML monitors file included by Umbriel.

    *ids* mappa la descrizione normalizzata nel ``config_name`` dei monitor
    collegati (vedi ``umbriel_ids``); *preferred* il loro modo preferito (vedi
    ``umbriel_preferred``).
    """
    selectors = _selectors(profile.monitors, use_description, ids)
    blocks: list[str] = []
    seen: set[str] = set()
    for monitor, selector in zip(profile.monitors, selectors):
        if selector.lower() in seen:
            # Ancora duplicato dopo il fallback: meglio omettere che rompere il file
            continue
        seen.add(selector.lower())
        pref = _preferred_mode(monitor, use_description, preferred)
        blocks.append("\n".join(_output_lines(monitor, selector, pref)))
    return HEADER + "\n\n" + "\n\n".join(blocks) + "\n"


def write_umbriel_config(
    profile: Profile, use_description: bool,
    ids: dict[str, str] | None = None,
    preferred: dict[str, str] | None = None,
) -> None:
    """Write the Umbriel monitors file (backing up the previous one)."""
    path = umbriel_monitors_path()
    backup_file(path)
    write_text(
        path, generate_umbriel_config(profile, use_description, ids, preferred))


def read_output_settings(text: str) -> dict[str, dict]:
    """Return the ``[output.*]`` tables of *text*, keyed by lower-case selector.

    Testo non valido: nessuna impostazione (il file è solo un'ottimizzazione
    per ripristinare ciò che l'IPC non riporta).
    """
    try:
        tables = tomllib.loads(text).get("output", {})
    except tomllib.TOMLDecodeError:
        return {}
    if not isinstance(tables, dict):
        return {}
    return {k.lower(): v for k, v in tables.items() if isinstance(v, dict)}


def _settings_for(monitor: MonitorConfig, tables: dict[str, dict]) -> dict:
    """Return the output table of *monitor*: identity first, then connector."""
    identity = monitor.niri_native_description() if monitor.description else None
    for selector in (identity, monitor.name):
        if selector and selector.lower() in tables:
            return tables[selector.lower()]
    return {}


def restore_config_settings(monitors: list[MonitorConfig], text: str) -> None:
    """Refill from monitors.toml what Umbriel's IPC does not report.

    L'IPC dà solo lo stato vivo: senza questo un apply dalla GUI perderebbe
    focus_at_startup, la policy VRR, l'HDR e la profondità colore.  Un campo
    assente dal file resta com'è (lo stato vivo vale più di un default).
    """
    tables = read_output_settings(text)
    for monitor in monitors:
        table = _settings_for(monitor, tables)
        monitor.focus_at_startup = table.get("focus_at_startup") is True
        if "vrr" in table:
            monitor.vrr = _VRR_FROM_POLICY.get(table["vrr"], VRR.OFF)
        if "hdr" in table:
            monitor.color_management = "hdr" if table["hdr"] == "on" else ""
        if table.get("bit_depth") in (8, 10):
            monitor.bitdepth = table["bit_depth"]


# ── include in config.toml ───────────────────────────────────────────────

class UmbrielConfigError(RuntimeError):
    """config.toml cannot be wired to the monitors file.

    È un RuntimeError: la GUI e il demone già gestiscono gli errori di
    apply_profile() con quel ramo (ripristino dei backup e segnalazione).
    """


# Commento sopra la riga ``files`` gestita: distingue il nostro include da
# quello dell'utente quando il nome del file cambia
MARKER_PREFIX = "# Monique monitor configuration: "

# Cartelle di sistema dove i pacchetti installano ``umbriel/config.toml``
SYSTEM_DATA_DIRS = ("/usr/share", "/usr/local/share")

# Chiavi di ``[output.*]`` che Monique genera: il file che include vince su
# quelli inclusi, quindi se restassero in config.toml annullerebbero ogni profilo
MANAGED_KEYS = (
    "enabled", "mode", "position", "scale", "transform", "vrr", "hdr",
    "bit_depth", "focus_at_startup",
)

_INCLUDE = ("include",)
_OPTIONAL = ("include", "optional")

_MARKER_RE = re.compile(r"^\s*" + re.escape(MARKER_PREFIX) + r"(.+?)\s*$")
_FILES_RE = re.compile(r"^(\s*files\s*=\s*)(\[.*\])(\s*(?:#.*)?)$")
_HEADER_RE = re.compile(r"^\s*(\[\[?)(?!\[)(.+?)(\]\]?)\s*(?:#.*)?$")
_MANAGED_KEY_RE = re.compile(
    r"^\s*(?:%s)\s*=" % "|".join(re.escape(k) for k in MANAGED_KEYS)
)


def _xdg_dirs(var: str, default: str) -> list[str]:
    return [d for d in os.environ.get(var, default).split(":") if d]


def find_packaged_config() -> Path | None:
    """Return the first packaged ``umbriel/config.toml`` found, if any."""
    roots = [
        *_xdg_dirs("XDG_CONFIG_DIRS", "/etc/xdg"),
        *_xdg_dirs("XDG_DATA_DIRS", "/usr/local/share:/usr/share"),
        *SYSTEM_DATA_DIRS,
    ]
    for root in roots:
        candidate = Path(root) / "umbriel" / "config.toml"
        if candidate.is_file():
            return candidate
    return None


def _parse(text: str, what: str) -> dict:
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise UmbrielConfigError(f"{what} is not valid TOML: {e}") from e


def _header_path(line: str) -> tuple[str, ...] | None:
    """Return the table path of a ``[a.b]`` header line, None for other lines."""
    match = _HEADER_RE.match(line)
    if not match:
        return None
    try:
        # Anche le tabelle di array ``[[a.b]]`` aprono una sezione
        opener, name, closer = match.groups()
        node = tomllib.loads(f"{opener}{name}{closer}\n")
    except tomllib.TOMLDecodeError:
        return None
    path: list[str] = []
    while isinstance(node, dict) and len(node) == 1:
        key, node = next(iter(node.items()))
        path.append(key)
    return tuple(path)


def _line_sections(lines: list[str]) -> list[tuple[str, ...]]:
    """Return, for every line, the path of the table it belongs to."""
    current: tuple[str, ...] = ()
    sections: list[tuple[str, ...]] = []
    for line in lines:
        header = _header_path(line)
        if header is not None:
            current = header
        sections.append(current)
    return sections


def _swap_entry(files: list[str], old: str, new: str) -> list[str]:
    """Replace *old* with *new* in place, keeping the list free of repeats."""
    swapped = [new if f == old else f for f in files]
    return list(dict.fromkeys(swapped))


def _render_files(prefix: str, files: list[str], suffix: str) -> str:
    return prefix + "[" + ", ".join(_quote(f) for f in files) + "]" + suffix


def _split_files_line(line: str) -> tuple[str, list[str], str]:
    """Split a single-line ``files = [...]`` into prefix, entries and tail."""
    match = _FILES_RE.match(line.rstrip("\n"))
    if not match:
        raise UmbrielConfigError(
            "Cannot edit config.toml: put the 'files' list of [include] on one line")
    prefix, array, suffix = match.groups()
    entries = _parse("x = " + array, "files list")["x"]
    if not all(isinstance(e, str) for e in entries):
        raise UmbrielConfigError("config.toml: 'files' must be a list of strings")
    return prefix, entries, suffix


def _find_managed(
    lines: list[str], sections: list[tuple[str, ...]],
) -> tuple[int, str] | None:
    """Return (marker line index, target) of Monique's managed include."""
    for i, line in enumerate(lines[:-1]):
        match = _MARKER_RE.match(line)
        if match and sections[i + 1] in (_INCLUDE, _OPTIONAL):
            return i, match.group(1)
    return None


def _drop_managed_keys(
    lines: list[str], sections: list[tuple[str, ...]],
) -> list[str]:
    """Remove the keys Monique manages from the ``[output.<name>]`` tables."""
    return [
        line for line, sec in zip(lines, sections)
        if not (len(sec) == 2 and sec[0] == "output"
                and _MANAGED_KEY_RE.match(line))
    ]


def _table(data: dict, path: tuple[str, ...]) -> dict:
    node = data
    for key in path:
        node = node.setdefault(key, {})
        if not isinstance(node, dict):
            raise UmbrielConfigError(f"config.toml: {'.'.join(path)} is not a table")
    return node


def _listed(data: dict, rel_name: str) -> bool:
    """True when the user lists *rel_name* in either include list."""
    inc = data.get("include")
    if not isinstance(inc, dict):
        return False
    opt = inc.get("optional")
    lists = [inc.get("files"), opt.get("files") if isinstance(opt, dict) else None]
    return any(isinstance(f, list) and rel_name in f for f in lists)


def _rename_include(
    lines: list[str], at: int, old: str, rel_name: str,
) -> list[str]:
    prefix, entries, suffix = _split_files_line(lines[at + 1])
    out = list(lines)
    out[at] = MARKER_PREFIX + rel_name + "\n"
    out[at + 1] = _render_files(prefix, _swap_entry(entries, old, rel_name), suffix) + "\n"
    return out


def _add_include(
    lines: list[str], sections: list[tuple[str, ...]], data: dict, rel_name: str,
) -> list[str]:
    """Add *rel_name* to the end of ``[include.optional] files``."""
    marker = MARKER_PREFIX + rel_name + "\n"
    header = next(
        (i for i, ln in enumerate(lines)
         if sections[i] == _OPTIONAL and _header_path(ln) == _OPTIONAL), None)
    if header is None:
        body = list(lines)
        if body and not body[-1].endswith("\n"):
            body[-1] += "\n"
        sep = ["\n"] if body else []
        return [*body, *sep, "[include.optional]\n", marker,
                _render_files("files = ", [rel_name], "") + "\n"]

    files_at = next(
        (i for i, ln in enumerate(lines)
         if sections[i] == _OPTIONAL and _FILES_RE.match(ln.rstrip("\n"))), None)
    if files_at is None:
        if "files" in data.get("include", {}).get("optional", {}):
            raise UmbrielConfigError(
                "Cannot edit config.toml: put the 'files' list of "
                "[include.optional] on one line")
        new = [marker, _render_files("files = ", [rel_name], "") + "\n"]
        return [*lines[:header + 1], *new, *lines[header + 1:]]

    prefix, entries, suffix = _split_files_line(lines[files_at])
    new_line = _render_files(prefix, [*entries, rel_name], suffix) + "\n"
    return [*lines[:files_at], marker, new_line, *lines[files_at + 1:]]


def _expected(
    data: dict, rel_name: str, old: str | None, strip: bool,
    section: tuple[str, ...],
) -> dict:
    """The parsed config.toml the edit must produce, built from the original."""
    want = copy.deepcopy(data)
    if strip:
        for table in (want.get("output") or {}).values():
            if isinstance(table, dict):
                for key in MANAGED_KEYS:
                    table.pop(key, None)
    node = _table(want, section)
    files = node.get("files", [])
    node["files"] = (
        _swap_entry(files, old, rel_name) if old else [*files, rel_name]
    )
    return want


def _edit_config(text: str, data: dict, rel_name: str) -> str | None:
    """Return the edited text, or None when config.toml is already right."""
    lines = text.splitlines(keepends=True)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    sections = _line_sections(lines)
    managed = _find_managed(lines, sections)

    if managed is None:
        if _listed(data, rel_name):
            return None
        stripped = _drop_managed_keys(lines, sections)
        edited = _add_include(stripped, _line_sections(stripped), data, rel_name)
        section, old, strip = _OPTIONAL, None, True
    else:
        at, old = managed
        section, strip = sections[at + 1], False
        if old == rel_name:
            return None
        edited = _rename_include(lines, at, old, rel_name)

    result = "".join(edited)
    want = _expected(data, rel_name, old, strip, section)
    if _parse(result, "the edited config.toml") != want:
        raise UmbrielConfigError(
            "Cannot safely edit config.toml (unsupported layout, e.g. dotted "
            "output keys or an inline include table); add the include of "
            f"{rel_name!r} by hand")
    return result


def _read_utf8(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError as e:
        raise UmbrielConfigError(f"{path} is not valid UTF-8: {e}") from e


def _initial_text(config: Path) -> str | None:
    """Return config.toml's text, copying the packaged one when it is missing.

    None: custom config dir without a config.toml, which the user wires by hand.
    """
    if config.exists():
        return _read_utf8(config)
    if is_config_dir_overridden():
        return None
    packaged = find_packaged_config()
    if packaged is None:
        log.warning("No packaged Umbriel config.toml found to copy")
        raise UmbrielConfigError(
            f"{config} does not exist and no packaged Umbriel config.toml was "
            "found to start from; create it and include the monitors file")
    return _read_utf8(packaged)


def ensure_umbriel_include() -> bool:
    """Make config.toml include the monitors file Monique generates.

    Senza config.toml parte da una copia di quello pacchettizzato (uno stub lo
    oscurerebbe e farebbe perdere i tasti).  Al primo avvio toglie dalle
    tabelle ``[output.*]`` le chiavi che Monique gestisce.  Il risultato è
    verificato con tomllib; in caso di dubbio non scrive nulla e solleva
    ``UmbrielConfigError``.  Con ``--config-dir`` e senza config.toml non fa
    nulla: lo collega l'utente.

    Returns True if config.toml was written.
    """
    config = umbriel_user_config_path()
    text = _initial_text(config)
    if text is None:
        return False

    rel_name = f"{get_monitor_config_name()}.toml"
    edited = _edit_config(text, _parse(text, str(config)), rel_name)
    if edited is None:
        if config.exists():
            return False
        edited = text  # copia pacchettizzata che include già il file

    backup_file(config)
    write_text(config, edited)
    return True
