"""Serializzazione dei profili salvati in un config kanshi.

kanshi legge un solo file (``include`` a parte) e sceglie da solo il profilo:
il primo, in ordine di file, i cui output coincidono esattamente con i monitor
collegati.  Qui tutti i profili salvati finiscono in un unico file, con il
profilo appena applicato in testa; gli altri restano raggiungibili con
``kanshictl switch <nome>``.

Il modulo non importa ``gi`` e non aggiunge nulla a ``MonitorConfig``.
"""

from __future__ import annotations

import re
from pathlib import Path

from .models import MonitorConfig, PositionMode, Profile, ResolutionMode, ScaleMode
from .profile_manager import ProfileManager
from .utils import (
    backup_file,
    get_monitor_config_name,
    kanshi_config_dir,
    write_text,
)

HEADER = "# Generated by Monique: https://github.com/ToRvaLDz/monique"

# kanshi confronta i criteri con "<make> <model> <serial>" via fnmatch()
_FNMATCH_SPECIAL = re.compile(r"([*?\[\\])")
_CONTROL_CHARS = re.compile(r"[\x00-\x1f\x7f]")


def kanshi_monitors_path() -> Path:
    """Return the kanshi monitor config file (``<name>.kanshi``)."""
    return kanshi_config_dir() / f"{get_monitor_config_name()}.kanshi"


def _quote(text: str) -> str:
    """Quote *text* as an scfg word.

    I caratteri di controllo (a capo compreso) diventano uno spazio: un nome
    modificato a mano non deve poter spezzare il file.
    """
    flat = _CONTROL_CHARS.sub(" ", text)
    return '"' + flat.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _fnmatch_escape(text: str) -> str:
    return _FNMATCH_SPECIAL.sub(r"\\\1", text)


def _is_pnp_id(make: str) -> bool:
    """Three upper-case letters, with or without Niri's ``PNP(...)`` wrapper."""
    bare = make[4:-1] if make.startswith("PNP(") and make.endswith(")") else make
    return len(bare) == 3 and bare.isalpha() and bare.isupper()


def _bare_vendor(make: str) -> str:
    if make.startswith("PNP(") and make.endswith(")"):
        return make[4:-1]
    return make


def _identity(monitor: MonitorConfig) -> str | None:
    """Return the fnmatch pattern for the monitor's make/model/serial.

    None quando non c'è un make da cui ricostruirlo.  Le descrizioni salvate
    non vanno bene: ``Unknown`` è stato tolto e non combacerebbero mai.
    """
    if not monitor.make:
        return None
    if _is_pnp_id(monitor.make):
        # Niri dice PNP(AOC), Hyprland e Sway dicono AOC: un pattern per tutti
        make = f"*{_fnmatch_escape(_bare_vendor(monitor.make))}*"
    else:
        make = _fnmatch_escape(monitor.make)
    model = _fnmatch_escape(monitor.model or "Unknown")
    serial = _fnmatch_escape(monitor.serial or "Unknown")
    return f"{make} {model} {serial}"


def _connector(monitor: MonitorConfig) -> str:
    """Connector name, or the description as the only identifier left."""
    return _fnmatch_escape(monitor.name or monitor.description)


def _criteria(monitors: list[MonitorConfig], use_description: bool) -> list[str]:
    """Return one kanshi criteria string per monitor.

    kanshi rifiuta due output con criteri identici nello stesso profilo con un
    errore di parsing che rompe l'intero file: i gemelli senza seriale
    ricadono sui nomi dei connettori.
    """
    if use_description:
        picked = [_identity(m) or _connector(m) for m in monitors]
    else:
        picked = [_connector(m) for m in monitors]

    counts = {c: picked.count(c) for c in picked}
    return [
        _connector(m) if counts[c] > 1 else c
        for m, c in zip(monitors, picked)
    ]


def _output_block(monitor: MonitorConfig, criteria: str) -> list[str]:
    head = f"    output {_quote(criteria)}"
    if not monitor.enabled:
        return [f"{head} disable"]

    lines = [f"{head} {{", "        enable"]
    if monitor.resolution_mode == ResolutionMode.EXPLICIT:
        lines.append(
            f"        mode {monitor.width}x{monitor.height}"
            f"@{monitor.refresh_rate:.3f}Hz"
        )
    elif monitor.resolution_mode == ResolutionMode.PREFERRED:
        lines.append("        mode preferred")
    # HIGHRES/HIGHRR non hanno un equivalente in kanshi
    if monitor.position_mode == PositionMode.EXPLICIT:
        lines.append(f"        position {monitor.x},{monitor.y}")
    if monitor.scale_mode == ScaleMode.EXPLICIT:
        lines.append(f"        scale {monitor.scale:g}")
    # kanshi passa il valore al protocollo: serve l'ordine del protocollo,
    # non la tabella invertita di Sway
    lines.append(
        f"        transform {MonitorConfig._NIRI_TRANSFORMS[monitor.transform.value]}"
    )
    lines.append("    }")
    return lines


def _profile_block(profile: Profile, use_description: bool) -> list[str]:
    criteria = _criteria(profile.monitors, use_description)
    head = f"profile {_quote(profile.name)} {{" if profile.name else "profile {"
    lines = [head]
    seen: set[str] = set()
    for monitor, crit in zip(profile.monitors, criteria):
        if crit in seen:
            # Ancora duplicato dopo il fallback: meglio omettere che rompere il file
            continue
        seen.add(crit)
        lines.extend(_output_block(monitor, crit))
    lines.append("}")
    return lines


def generate_kanshi_config(profiles: list[Profile], use_description: bool) -> str:
    """Serialize *profiles*, in the given order, as one kanshi config.

    Profili senza monitor o con tutti i monitor spenti sono saltati: kanshi
    lascerebbe la sessione al buio e non ha la protezione di moniqued.
    """
    lines = [HEADER]
    for profile in profiles:
        if not any(m.enabled for m in profile.monitors):
            continue
        lines.extend(_profile_block(profile, use_description))
    return "\n".join(lines) + "\n"


def write_kanshi_config(applied: Profile, use_description: bool) -> None:
    """Write every saved profile to the kanshi file, *applied* first.

    Il profilo applicato sostituisce l'omonimo salvato e va in testa (kanshi
    sceglie il primo che combacia); gli altri seguono per ``last_applied_time``
    decrescente.
    """
    path = kanshi_monitors_path()
    saved = [p for p in ProfileManager().list_all() if p.name != applied.name]
    saved.sort(key=lambda p: p.last_applied_time, reverse=True)

    backup_file(path)
    write_text(path, generate_kanshi_config([applied, *saved], use_description))
